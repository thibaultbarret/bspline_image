"""Generate tests/data/scipy_reference.inc from scipy.ndimage.map_coordinates.

Usage (never run by CMake; the generated file is committed):
    python3 -m venv .venv-tools && .venv-tools/bin/pip install numpy scipy
    .venv-tools/bin/python -I tools/generate_scipy_reference.py > tests/data/scipy_reference.inc
"""
import math
import sys

import numpy as np
import scipy
from scipy.ndimage import map_coordinates

WIDTH, HEIGHT, COUNT, SEED = 9, 7, 60, 20261113
X_RANGE, Y_RANGE = (-4.0, 12.0), (-4.0, 10.0)
HALF_INTEGER_MARGIN = 1e-6
MAX_ORDER = 5
PER_LINE = 4


def smooth_pixel(i, j):
    return 100.0 + 50.0 * math.sin(0.7 * i + 0.3 * j) + 30.0 * math.cos(0.45 * j - 0.2 * i)


def near_half_integer(v):
    return abs((v - math.floor(v)) - 0.5) < HALF_INTEGER_MARGIN


def draw_points(rng):
    xs, ys = [], []
    while len(xs) < COUNT:
        x = rng.uniform(*X_RANGE)
        y = rng.uniform(*Y_RANGE)
        if near_half_integer(x) or near_half_integer(y):
            continue
        xs.append(x)
        ys.append(y)
    return np.array(xs), np.array(ys)


def fmt_lines(values, indent):
    chunks = [", ".join("%.17g" % v for v in values[k:k + PER_LINE])
              for k in range(0, len(values), PER_LINE)]
    return (",\n" + indent).join(chunks)


def fmt_array(name, values):
    return "inline constexpr double %s[%d] = {\n    %s};\n" % (
        name, len(values), fmt_lines(values, "    "))


def main():
    # Array is indexed [row=j, col=i] = smooth_pixel(i, j).
    img = np.array([[smooth_pixel(i, j) for i in range(WIDTH)] for j in range(HEIGHT)])
    xs, ys = draw_points(np.random.default_rng(SEED))
    versions = "numpy %s, scipy %s" % (np.__version__, scipy.__version__)
    print("generated with %s" % versions, file=sys.stderr)

    rows = []
    for order in range(MAX_ORDER + 1):
        # SciPy coordinate order is (row, col) = (y, x).
        vals = map_coordinates(img, [ys, xs], order=order, mode="mirror", prefilter=True)
        rows.append("    {" + fmt_lines(vals, "     ") + "}")

    out = [
        "// SPDX-License-Identifier: BSD-3-Clause\n",
        "// Generated by tools/generate_scipy_reference.py -- do not edit.\n",
        "// Reference: scipy.ndimage.map_coordinates(mode='mirror', prefilter=True), orders 0-5.\n",
        "// Generated with %s; rng seed %d.\n" % (versions, SEED),
        "#pragma once\n\n#include <cstddef>\n\nnamespace bsi_test::scipy_ref {\n\n",
        "inline constexpr std::ptrdiff_t ref_width = %d;\n" % WIDTH,
        "inline constexpr std::ptrdiff_t ref_height = %d;\n" % HEIGHT,
        "inline constexpr std::ptrdiff_t ref_count = %d;\n\n" % COUNT,
        fmt_array("ref_image", img.ravel()) + "\n",
        fmt_array("ref_x", xs) + "\n",
        fmt_array("ref_y", ys) + "\n",
        "inline constexpr double ref_values[%d][%d] = {\n%s};\n\n"
        % (MAX_ORDER + 1, COUNT, ",\n".join(rows)),
        "}  // namespace bsi_test::scipy_ref\n",
    ]
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
